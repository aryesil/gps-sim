"""Golden vector / memory image generator for the FPGA GNSS synthesizer RTL.

Usage (repo root):
    PYTHONPATH=. python scripts/fpga_vectors.py mem        # fpga/mem/*.mem
    PYTHONPATH=. python scripts/fpga_vectors.py cmdfmt     # fpga/rtl/gs_cmdfmt.vh
    PYTHONPATH=. python scripts/fpga_vectors.py case NAME  # fpga/vec/NAME_*
    PYTHONPATH=. python scripts/fpga_vectors.py case all

File formats (all text, one entry per line, lowercase hex, $readmemh ready)
  fpga/mem/gs_rom.mem          17856 lines, 32-bit code ROM word, rom_layout()
                               order (kind, then PRN), chip i = bit i%32 of
                               word i//32, bit 1 = chip +1.
  fpga/mem/gs_base.mem         256 lines, 16-bit base word address, index
                               {kind[1:0], prn[5:0]}; 0 for unused entries.
  fpga/mem/gs_sincos.mem       1024 lines `cccc`: quarter-wave cos values
                               roms._TABLE[0][r], r = 0..1023, int16 two's
                               complement (4 hex digits).
  fpga/mem/gs_sincos_full.mem  4096 lines `ccccssss`, same packing, index idx =
                               0..4095 from roms.table_value(idx).
  fpga/vec/<name>_cmd.hex      32-bit command words (CFG record then BLOCK
                               records), one per line, 8 hex digits.
  fpga/vec/<name>_exp.hex      expected output, one line `iiiiqqqq` per sample
                               (int16 I then Q, 4 hex digits each), blocks
                               concatenated as returned by EngineModel.
  fpga/vec/<name>_term.hex     (ca1, e1b, e1c, b1i only) per-sample sum over
                               channels of model.channel_terms: ONE line per
                               sample `iiiiiiiiiiqqqqqqqqqq`, I and Q each a
                               38-bit two's complement value in 10 hex digits
                               (the top 2 bits of the 40 are zero).
  fpga/vec/<name>_cnt.txt      expected model counters, `key=value` lines
                               (underruns, dropped_late, clipped).

Cases: ca1 e1b e1c b1i (single channel, 2 blocks), gce12 (12 channels,
2 blocks), gce45 (whole GCE plan, 1 block), gapcase (gce12 blocks 0,1,3),
latecase (gce12 blocks 0,1 then block 0 again), maxch (64 synthetic channels,
1 block).  Plan cases use fs = 30 Msps and the standard test scenario of
tests/fpga/test_cmdgen.py.

Pipe test vectors (ca1 e1b e1c b1i, and `pair` = ca1 channel in slot 0 + e1c
channel in slot 1, 2 blocks each):
  fpga/vec/<name>_par.hex  one packed PAR record (gs_defs.vh, 173 bit =
                           44 hex digits) per line, block-major, channel
                           (slot) minor: line = block*NCH + slot.
  fpga/vec/<name>_st.hex   same order, packed ST record (148 bit = 37 digits).
  fpga/vec/pair_term.hex   same format as <name>_term.hex.
`pack_par(chan)` / `pack_st(chan)` return python ints following gs_defs.vh.
"""
from __future__ import annotations

import argparse
import datetime as dt
import pathlib
import struct
import sys
import types

import numpy as np

from backend.fpga import cmdfmt, roms
from backend.fpga import widths as W
from backend.fpga.cmdgen import generate_blocks
from backend.fpga.model import EngineModel

ROOT = pathlib.Path(__file__).resolve().parents[1]
MEM_DIR = ROOT / "fpga" / "mem"
VEC_DIR = ROOT / "fpga" / "vec"
VH_PATH = ROOT / "fpga" / "rtl" / "gs_cmdfmt.vh"
B = W.BLOCK
RINEX = ROOT / "data" / "rinex" / "BRDC_2026289.rnx"
FS = 30e6
CASES = ["ca1", "e1b", "e1c", "b1i", "gce12", "gce45", "gapcase", "latecase", "maxch"]
PIPE_CASES = ["ca1", "e1b", "e1c", "b1i"]     # + "pair" (see write_pair)


def _wr(path, lines):
    path = pathlib.Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


# ------------------------------------------------------------------ mem
def write_rom_mem(d=MEM_DIR):
    d = pathlib.Path(d)
    d.mkdir(parents=True, exist_ok=True)
    _wr(d / "gs_rom.mem", [f"{int(w):08x}" for w in roms.all_rom_words()])
    # tail of the ROM (words 16384..): gs_scan maps it as a separate small BRAM
    _wr(d / "gs_rom_hi.mem", [f"{int(w):08x}" for w in roms.all_rom_words()][16384:])
    base = np.zeros(256, np.uint32)
    for (kind, prn), (b, _) in roms.rom_layout().items():
        base[(kind << 6) | prn] = b
    _wr(d / "gs_base.mem", [f"{int(w):04x}" for w in base])
    c, _ = roms._TABLE
    _wr(d / "gs_sincos.mem", [f"{int(x) & 0xFFFF:04x}" for x in c])
    full = [roms.table_value(i) for i in range(roms.FULL)]
    _wr(d / "gs_sincos_full.mem",
        [f"{x & 0xFFFF:04x}{y & 0xFFFF:04x}" for x, y in full])


# --------------------------------------------------------------- cmdfmt.vh
def cmdfmt_vh() -> str:
    out = ["// Generated by scripts/fpga_vectors.py cmdfmt from backend/fpga/cmdfmt.py",
           "// DO NOT EDIT.  Field bit ranges inside the 320-bit channel record.",
           "`ifndef GS_CMDFMT_VH", "`define GS_CMDFMT_VH",
           f"`define GS_CH_BITS {cmdfmt.CH_WORDS * 32}",
           f"`define GS_CH_WORDS {cmdfmt.CH_WORDS}",
           f"`define GS_CMD_MAGIC 8'h{cmdfmt.MAGIC_BYTE:02X}",
           f"`define GS_TYPE_CFG 8'd{cmdfmt.TYPE_CFG}",
           f"`define GS_TYPE_BLOCK 8'd{cmdfmt.TYPE_BLOCK}",
           f"`define GS_CFG_WORDS {cmdfmt.CFG_WORDS}",
           f"`define GS_BLOCK_HDR_WORDS {cmdfmt.BLOCK_HDR_WORDS}"]
    for name, (off, wid) in cmdfmt._CH_FIELDS.items():
        n = name.upper()
        out.append(f"`define GS_F_{n}_LO {off}")
        out.append(f"`define GS_F_{n}_HI {off + wid - 1}")
    out.append("`endif")
    return "\n".join(out) + "\n"


def write_cmdfmt_vh(path=VH_PATH):
    pathlib.Path(path).parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="\n") as f:
        f.write(cmdfmt_vh())


# ------------------------------------------------- packed pipe records
def pack_par(c) -> int:
    """PAR record of gs_defs.vh (173 bit) from a cmdfmt.ChannelBlock."""
    cb = {0: 0, 1: 1, -1: 2}[c.cboc]
    m18 = (1 << W.COEF_BITS) - 1
    v = (int(bool(c.valid)) | (int(c.boc) & 1) << 1 | cb << 2 | c.kind << 4
         | c.prn << 6 | (c.carr_inc & 0xFFFFFFFF) << 12
         | (c.code_inc & ((1 << 43) - 1)) << 44 | c.sign_bits << 87
         | (c.coef[0] & m18) << 119 | (c.coef[1] & m18) << 137
         | (c.coef[2] & m18) << 155)
    return v


def pack_st(c) -> int:
    """ST record of gs_defs.vh (148 bit) from a cmdfmt.ChannelBlock."""
    lim = c.code_len << W.CODE_FRAC_BITS
    assert 0 <= c.sign_phase0 < lim and 0 <= c.code_phase0 < lim
    return (c.carr_phase0 | c.code_phase0 << 32 | c.sign_phase0 << 84
            | c.sign_idx0 << 136 | (c.code_phase0 >> 45) << 141)


def write_pipe_vectors(name, blocks, d=VEC_DIR):
    """blocks = [(idx, [ChannelBlock])]; slot = list position."""
    par = [f"{pack_par(c):044x}" for _, ch in blocks for c in ch]
    st = [f"{pack_st(c):037x}" for _, ch in blocks for c in ch]
    _wr(pathlib.Path(d) / f"{name}_par.hex", par)
    _wr(pathlib.Path(d) / f"{name}_st.hex", st)


def block_terms(m, blocks):
    ti, tq = [], []
    for _, chans in blocks:
        si = np.zeros(B, np.int64)
        sq = np.zeros(B, np.int64)
        for c in chans:
            _, a, b, _ = m.channel_terms(c)
            si += a
            sq += b
        ti.append(si)
        tq.append(sq)
    return np.concatenate(ti), np.concatenate(tq)


def write_pair(d=VEC_DIR):
    """Two channels (ca1 in slot 0, e1c in slot 1) summed, 2 blocks."""
    ba = build_case("ca1")["feed"]
    bb = build_case("e1c")["feed"]
    blocks = [(i, ba[i][1] + bb[i][1]) for i in range(2)]
    m = EngineModel(FS)
    ti, tq = block_terms(m, blocks)
    write_term_vector("pair", ti, tq, d)
    write_pipe_vectors("pair", blocks, d)
    return dict(name="pair", samples=len(ti))


# -------------------------------------------------------------- vectors
def check_records(chans):
    """Host guarantee the RTL relies on: phases below code_len << 40."""
    for c in chans:
        lim = c.code_len << W.CODE_FRAC_BITS
        assert 0 <= c.sign_phase0 < lim, ("sign_phase0", c.ch, c.sign_phase0, lim)
        assert 0 <= c.code_phase0 < lim, ("code_phase0", c.ch, c.code_phase0, lim)
        assert 0 <= c.sign_idx0 < W.SIGN_BITS


def words_of(data: bytes):
    return struct.unpack(f"<{len(data) // 4}I", data)


def write_cmd_vector(name, words, d=VEC_DIR):
    _wr(pathlib.Path(d) / f"{name}_cmd.hex",
        [f"{int(w) & 0xFFFFFFFF:08x}" for w in words])


def write_out_vector(name, out, d=VEC_DIR):
    out = np.asarray(out).reshape(-1, 2).astype(np.int64)
    _wr(pathlib.Path(d) / f"{name}_exp.hex",
        [f"{i & 0xFFFF:04x}{q & 0xFFFF:04x}" for i, q in out])


def write_term_vector(name, ti, tq, d=VEC_DIR):
    m = (1 << 38) - 1
    _wr(pathlib.Path(d) / f"{name}_term.hex",
        [f"{int(i) & m:010x}{int(q) & m:010x}" for i, q in zip(ti, tq)])


def write_cnt(name, m: EngineModel, d=VEC_DIR):
    _wr(pathlib.Path(d) / f"{name}_cnt.txt",
        [f"underruns={m.underruns}", f"dropped_late={m.dropped_late}",
         f"clipped={m.clipped}"])


def cmd_words(blocks, nch, fs, shift=0, start_block=0):
    """CFG record + BLOCK records; blocks = [(idx, [ChannelBlock])]."""
    data = cmdfmt.pack_cfg(cmdfmt.CfgCommand(nch, int(fs), shift, start_block))
    for idx, chans in blocks:
        check_records(chans)
        data += cmdfmt.pack_block(idx, chans)
    return words_of(data)


# ---------------------------------------------------------------- scenes
_PLAN = None


def plan_band():
    global _PLAN
    if _PLAN is None:
        from backend.scenario import ScenarioRequest
        from backend.synth import engine
        req = ScenarioRequest(
            rinex_path=str(RINEX), lat=41.0, lon=29.0, alt=100.0,
            start=dt.datetime(2026, 10, 16, 12), in_memory=True, duration_s=0.1,
            sample_rate=FS, sample_format="int16", systems=("G", "C", "E"))
        _PLAN = engine.plan(req).bands[0]
    return _PLAN


def band_of(svs, fs, nblocks, owner):
    return types.SimpleNamespace(fs=fs, block_samples=B, total_samples=nblocks * B,
                                 svs=list(svs), keep_alive=owner.keep_alive)


def _fit(band, lvl=32767.0):
    while True:
        try:
            generate_blocks(band, n_blocks=0, out_lsb=lvl)
            return lvl
        except ValueError as e:
            if "does not fit" not in str(e):
                raise
            lvl *= 0.97


def _pick(band, sysc, nav, sec_len=None):
    for s in band.svs:
        if s.sys == sysc and (s.nav_mode != 0) == nav and \
                (sec_len is None or s.sec_len == sec_len):
            return s
    raise AssertionError("channel kind not in plan")


def _blocks(sub, nb, lvl):
    return list(generate_blocks(sub, n_blocks=nb, out_lsb=lvl))


def _mixed12(band):
    def pick(pred, n):
        return [s for s in band.svs if pred(s)][:n]
    svs = (pick(lambda s: s.sys == 0, 4)
           + pick(lambda s: s.sys == 5 and s.nav_mode != 0, 2)
           + pick(lambda s: s.sys == 5 and s.nav_mode == 0, 2)
           + pick(lambda s: s.sys == 3, 4))
    assert len(svs) == 12, len(svs)
    return svs


def maxch_block(seed=1234):
    """Synthetic 64-channel block 0 (kinds and PRNs cycle), no clipping."""
    rng = np.random.default_rng(seed)
    pmax = {0: 32, 1: 50, 2: 50, 3: 63}
    rate = {0: 1.023e6, 1: 1.023e6, 2: 1.023e6, 3: 2.046e6}
    chans = []
    for c in range(64):
        kind = c % 4
        prn = 1 + (c * 7 + c // 4) % pmax[kind]
        L = cmdfmt.CODE_LEN[kind]
        lim = L << W.CODE_FRAC_BITS
        boc = int(kind in (1, 2))
        cboc = (1 if kind == 1 else -1) if boc else 0
        rr = (rate[kind] + float(rng.uniform(-3e3, 3e3))) / FS
        chans.append(cmdfmt.ChannelBlock(
            ch=c, prn=prn, kind=kind, code_len=L, valid=True,
            carr_inc=int(rng.integers(-2**31, 2**31)),
            carr_phase0=int(rng.integers(0, 2**32)), code_inc=int(rr * (1 << 40)),
            code_phase0=int(rng.integers(0, lim)),
            sign_phase0=int(rng.integers(0, lim)),
            sign_idx0=int(rng.integers(0, 32)),
            sign_bits=int(rng.integers(0, 2**32)), boc=boc, cboc=cboc,
            coef=(int(rng.integers(50, 300)), int(rng.integers(50, 300)),
                  -int(rng.integers(50, 300)) if boc else int(rng.integers(50, 300)))))
    return [(0, chans)]


def build_case(name):
    """-> dict(sent=[(idx, chans)], feed=[(idx, chans)], nch, term)."""
    if name in ("ca1", "e1b", "e1c", "b1i"):
        band = plan_band()
        sv = {"ca1": lambda: _pick(band, 0, True),
              "e1b": lambda: _pick(band, 5, True, 0),
              "e1c": lambda: _pick(band, 5, False, 25),
              "b1i": lambda: _pick(band, 3, True, 20)}[name]()
        blocks = _blocks(band_of([sv], FS, 2, band), 2, 4096.0)
        return dict(sent=blocks, feed=blocks, nch=1, term=True)
    if name in ("gce12", "gapcase", "latecase"):
        band = plan_band()
        svs = _mixed12(band)
        nb = 4 if name == "gapcase" else 2
        sub = band_of(svs, FS, nb, band)
        blocks = _blocks(sub, nb, _fit(sub))
        if name == "gapcase":
            blocks = [blocks[0], blocks[1], blocks[3]]
        elif name == "latecase":
            blocks = blocks + [blocks[0]]
        return dict(sent=blocks, feed=blocks, nch=12, term=False)
    if name == "gce45":
        band = plan_band()
        sub = band_of(band.svs, FS, 1, band)
        blocks = _blocks(sub, 1, _fit(sub))
        return dict(sent=blocks, feed=blocks, nch=len(band.svs), term=False)
    if name == "maxch":
        blocks = maxch_block()
        return dict(sent=blocks, feed=blocks, nch=64, term=False)
    raise SystemExit(f"unknown case {name}; known: {' '.join(CASES)}")


def write_case(name, d=VEC_DIR):
    cs = build_case(name)
    m = EngineModel(FS)
    m.start(0)
    out = np.concatenate([m.feed_block(i, ch) for i, ch in cs["feed"]])
    write_cmd_vector(name, cmd_words(cs["sent"], cs["nch"], FS), d)
    write_out_vector(name, out, d)
    write_cnt(name, m, d)
    if cs["term"]:
        ti, tq = block_terms(m, cs["feed"])
        write_term_vector(name, ti, tq, d)
        write_pipe_vectors(name, cs["feed"], d)
    return dict(name=name, samples=len(out), underruns=m.underruns,
                dropped_late=m.dropped_late, clipped=m.clipped)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("cmd", choices=["mem", "cmdfmt", "case"])
    ap.add_argument("name", nargs="?")
    a = ap.parse_args(argv)
    if a.cmd == "mem":
        write_rom_mem()
    elif a.cmd == "cmdfmt":
        write_cmdfmt_vh()
    else:
        if not a.name:
            ap.error("case needs a name")
        if a.name == "pair":
            print(write_pair())
        else:
            for n in (CASES if a.name == "all" else [a.name]):
                print(write_case(n))
            if a.name == "all":
                print(write_pair())
    return 0


if __name__ == "__main__":
    sys.exit(main())
